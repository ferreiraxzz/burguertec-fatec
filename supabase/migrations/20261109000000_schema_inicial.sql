-- ---------------------------------------------------------------------
-- 7. Privilégios de tabela (defesa em profundidade além do RLS)
-- ---------------------------------------------------------------------
-- perfis: criado pelo trigger; o usuário só altera nome/telefone/cpf
-- (nunca is_admin nem id).
revoke all on public.perfis from anon;
revoke insert, update, delete on public.perfis from authenticated;
grant select on public.perfis to authenticated;
grant update (nome, telefone, cpf) on public.perfis to authenticated;

revoke all on public.enderecos from anon;
grant select, insert, update, delete on public.enderecos to authenticated;

-- pedidos: inserção só via RPC; admin só altera status.
revoke all on public.pedidos from anon;
revoke insert, update, delete on public.pedidos from authenticated;
grant select on public.pedidos to authenticated;
grant update (status) on public.pedidos to authenticated;

revoke all on public.itens_pedido from anon;
revoke insert, update, delete on public.itens_pedido from authenticated;
grant select on public.itens_pedido to authenticated;

revoke all on public.itens_pedido_adicionais from anon;
revoke insert, update, delete on public.itens_pedido_adicionais from authenticated;
grant select on public.itens_pedido_adicionais to authenticated;

-- avaliacoes: leitura pública RESTRITA POR COLUNA; inserção pelo dono.
--   REGRA: ninguém lê usuario_id pela API.
--     anon          -> só (nota, comentario, created_at).
--     authenticated -> (pedido_id, nota, comentario, created_at); o
--                      pedido_id é necessário para o dono saber quais
--                      pedidos já avaliou (filtro/embed via pedidos).
--   Como há privilégio por coluna, o front NÃO pode usar select('*') nem
--   insert(...).select() sem listar colunas permitidas.
--   O "revoke select" de tabela também remove grants de coluna antigos,
--   então reexecutar este bloco é seguro.
revoke all on public.avaliacoes from anon;
revoke select, update, delete on public.avaliacoes from authenticated;
grant select (nota, comentario, created_at) on public.avaliacoes to anon;
grant select (pedido_id, nota, comentario, created_at) on public.avaliacoes to authenticated;
grant insert on public.avaliacoes to authenticated;

-- catálogo: leitura pública; escrita filtrada pelo RLS (só admin).
grant select on public.categorias, public.produtos, public.adicionais to anon, authenticated;
grant insert, update, delete on public.categorias, public.produtos, public.adicionais to authenticated;


