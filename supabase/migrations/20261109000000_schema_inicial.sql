  for select to authenticated
  using (usuario_id = (select auth.uid()));

drop policy if exists "pedidos: admin le tudo" on public.pedidos;
create policy "pedidos: admin le tudo" on public.pedidos
  for select to authenticated
  using ((select public.is_admin()));

drop policy if exists "pedidos: admin altera status" on public.pedidos;
create policy "pedidos: admin altera status" on public.pedidos
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

-- 8.7 itens_pedido
drop policy if exists "itens_pedido: dono ou admin le" on public.itens_pedido;
create policy "itens_pedido: dono ou admin le" on public.itens_pedido
  for select to authenticated
  using (
    (select public.is_admin())
    or exists (
      select 1 from public.pedidos p
      where p.id = itens_pedido.pedido_id
        and p.usuario_id = (select auth.uid())
    )
  );

-- 8.8 itens_pedido_adicionais
drop policy if exists "itens_pedido_adicionais: dono ou admin le" on public.itens_pedido_adicionais;
create policy "itens_pedido_adicionais: dono ou admin le" on public.itens_pedido_adicionais
  for select to authenticated
  using (
    (select public.is_admin())
    or exists (
      select 1
      from public.itens_pedido i
      join public.pedidos p on p.id = i.pedido_id
      where i.id = itens_pedido_adicionais.item_id
        and p.usuario_id = (select auth.uid())
    )
  );

-- 8.9 avaliacoes
--   A policy libera todas as linhas para anon e authenticated, mas as
--   colunas visíveis são limitadas pelos grants da seção 7 (usuario_id
--   nunca; pedido_id só para authenticated).
drop policy if exists "avaliacoes: leitura publica" on public.avaliacoes;
create policy "avaliacoes: leitura publica" on public.avaliacoes
  for select to anon, authenticated
  using (true);

drop policy if exists "avaliacoes: dono avalia pedido entregue" on public.avaliacoes;
create policy "avaliacoes: dono avalia pedido entregue" on public.avaliacoes
  for insert to authenticated
  with check (
    usuario_id = (select auth.uid())
    and exists (
      select 1 from public.pedidos p
      where p.id = avaliacoes.pedido_id
        and p.usuario_id = (select auth.uid())
        and p.status = 'entregue'
    )
  );
