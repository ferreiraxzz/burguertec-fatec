create table if not exists public.produtos (
  id             text primary key,
  categoria_id   smallint not null references public.categorias (id) on delete restrict,
  nome           text not null,
  descricao      text,
  preco          numeric(10,2) not null check (preco >= 0),
  imagem_url     text,
  imagem_posicao text not null default 'bottom',
  permite_ponto  boolean not null default true,
  ativo          boolean not null default true,
  ordem          int not null default 0,
  created_at     timestamptz not null default now()
);

create table if not exists public.adicionais (
  id    text primary key,
  nome  text not null,
  preco numeric(10,2) not null check (preco >= 0),
  ativo boolean not null default true
);

create table if not exists public.perfis (
  id         uuid primary key references auth.users (id) on delete cascade,
  nome       text,
  telefone   text,
  cpf        text unique,
  is_admin   boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.enderecos (
  id          uuid primary key default gen_random_uuid(),
  usuario_id  uuid not null default auth.uid() references public.perfis (id) on delete cascade,
  apelido     text,
  cep         text not null,
  logradouro  text not null,
  numero      text not null,
  complemento text,
  bairro      text not null,
  cidade      text not null,
  uf          char(2) not null,
  principal   boolean not null default false,
  created_at  timestamptz not null default now()
);

create table if not exists public.pedidos (
  id              bigint generated always as identity primary key,
  usuario_id      uuid not null references public.perfis (id) on delete cascade,
  endereco_id     uuid references public.enderecos (id) on delete set null,
  status          public.status_pedido not null default 'recebido',
  forma_pagamento public.forma_pagamento not null,
  subtotal        numeric(10,2) not null default 0 check (subtotal >= 0),
  taxa_entrega    numeric(10,2) not null default 0 check (taxa_entrega >= 0),
  total           numeric(10,2) not null default 0 check (total >= 0),
  observacao      text,
  endereco_entrega jsonb,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- Snapshot do endereço no momento do pedido (NULL = retirada no balcão).
-- O "add column if not exists" cobre bancos onde a tabela já existia.
alter table public.pedidos add column if not exists endereco_entrega jsonb;
comment on column public.pedidos.endereco_entrega is
  'Snapshot do endereço (apelido, cep, logradouro, numero, complemento, bairro, cidade, uf). NULL = retirada no balcão.';

create table if not exists public.itens_pedido (
  id             bigint generated always as identity primary key,
  pedido_id      bigint not null references public.pedidos (id) on delete cascade,
  produto_id     text not null references public.produtos (id) on delete restrict,
  nome_produto   text not null,
  preco_unitario numeric(10,2) not null check (preco_unitario >= 0),
  quantidade     int not null check (quantidade > 0),
  ponto_carne    public.ponto_carne,
  observacao     text,
  subtotal       numeric(10,2) not null check (subtotal >= 0)
);

create table if not exists public.itens_pedido_adicionais (
  item_id      bigint not null references public.itens_pedido (id) on delete cascade,
  adicional_id text   not null references public.adicionais (id) on delete restrict,
  preco        numeric(10,2) not null check (preco >= 0),
  primary key (item_id, adicional_id)
);

create table if not exists public.avaliacoes (
  pedido_id  bigint primary key references public.pedidos (id) on delete cascade,
  usuario_id uuid not null default auth.uid() references public.perfis (id) on delete cascade,
  nota       smallint not null check (nota between 1 and 5),
  comentario text,
  created_at timestamptz not null default now()
);


